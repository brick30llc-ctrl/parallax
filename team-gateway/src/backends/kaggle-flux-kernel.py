"""parallax-flux: FLUX.1-schnell image batch on a Kaggle GPU notebook (T4 x2).

Generated by the Parallax team gateway: the gateway replaces the PROMPTS block below with the
pictures members asked for, pushes this script as a private kernel, waits for it to finish and
downloads the PNGs from /kaggle/working/out/. One pass, then the process exits so the session
stops (no idle GPU burn):
  1. pip-pin diffusers / transformers / accelerate (bitsandbytes only if the NF4 fallback runs)
  2. download FLUX.1-schnell (Apache-2.0) from a byte-identical, ungated HF mirror; no token
  3. encode all prompts once (CLIP + T5-XXL in bf16 on GPU 1), then free the text encoders
  4. denoise every prompt: 4 steps, guidance 0. Strategy 1 is the fp16 transformer sharded
     over both T4s (device_map="balanced"); strategy 2 is NF4 on one T4 if 1 fails or NaNs
  5. free the transformer, then decode all latents with the VAE in fp32 on a free GPU
  6. write PNGs and run.json (batch_id, prompt, seed, seconds, per-picture errors) into
     /kaggle/working/out/

Based on a tested FLUX.1-schnell batch pipeline. No secrets are used or printed: the model
is ungated and nothing is read from /kaggle/input. Prompts stay inside this private kernel.
"""
import gc
import json
import os
import subprocess
import sys
import threading
import time
import traceback

T0 = time.time()
TEST = os.environ.get("TWF_TEST") == "1"  # local CPU smoke test against a tiny random pipeline
OUT = os.environ.get("TWF_OUT", "/kaggle/working/out")
MODEL_DIR = os.environ.get("TWF_MODEL_DIR", "/tmp/flux-schnell")
WATCHDOG_MIN = 40          # hard stop so a hang cannot burn GPU quota (the gateway sets it)
STEPS, GUIDANCE, MAXSEQ = 4, 0.0, 256
VAE_SCALE = 8              # FLUX VAE downscale; the pipeline packs 2x2 latent patches on top
os.environ.setdefault("HF_HOME", "/tmp/hf")
os.environ.setdefault("HF_HUB_DISABLE_PROGRESS_BARS", "1")
os.environ.setdefault("HF_XET_HIGH_PERFORMANCE", "1")
os.environ.setdefault("TOKENIZERS_PARALLELISM", "false")
os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")

# Same weights as black-forest-labs/FLUX.1-schnell, which now needs a logged-in HF account.
# frankjoshua is the same git commit; unsloth matches every file blob except README/NOTICE.
# (verified 2026-10-17 through the public HF API: LFS sha256 of all 7 weight shards equal)
REPOS = [
    ("frankjoshua/FLUX.1-schnell", "741f7c3ce8b383c54771c7003378a50191e9efe9"),
    ("unsloth/FLUX.1-schnell", "9df3faa7ae3b6ddf0b2b69bb78616372897cc65c"),
    ("black-forest-labs/FLUX.1-schnell", "741f7c3ce8b383c54771c7003378a50191e9efe9"),
]
if TEST:
    REPOS = [("hf-internal-testing/tiny-flux-pipe", None)]
PATTERNS = ["model_index.json", "scheduler/*", "text_encoder/*", "text_encoder_2/*", "tokenizer/*",
            "tokenizer_2/*", "transformer/*", "vae/*"]
EXPECTED_BYTES = {
    "transformer/diffusion_pytorch_model-00001-of-00003.safetensors": 9962580296,
    "transformer/diffusion_pytorch_model-00002-of-00003.safetensors": 9949328904,
    "transformer/diffusion_pytorch_model-00003-of-00003.safetensors": 3870584832,
    "text_encoder_2/model-00001-of-00002.safetensors": 4994582224,
    "text_encoder_2/model-00002-of-00002.safetensors": 4530066360,
    "text_encoder/model.safetensors": 246144352,
    "vae/diffusion_pytorch_model.safetensors": 167666902,
}
PINS = ["diffusers==0.40.0", "transformers==5.18.0", "accelerate==1.14.0",
        "sentencepiece", "protobuf", "huggingface_hub>=1.31,<2"]
BNB_PIN = "bitsandbytes==0.50.1"

# <<PROMPTS
BATCH_ID = ""
PROMPTS = json.loads("[]")
# PROMPTS>>

RUN = {"batch_id": BATCH_ID, "model": "black-forest-labs/FLUX.1-schnell (ungated mirror)",
       "settings": {"steps": STEPS, "guidance": GUIDANCE, "max_sequence_length": MAXSEQ},
       "env": {}, "events": [], "images": [], "totals": {}}


def log(msg):
    print(f"[twf {time.strftime('%H:%M:%S')} +{int(time.time() - T0)}s] {msg}", flush=True)


def event(msg):
    RUN["events"].append({"t": round(time.time() - T0, 1), "msg": msg})
    log(msg)


def save_run(name="run.json"):
    os.makedirs(OUT, exist_ok=True)
    RUN["totals"]["wall_seconds"] = round(time.time() - T0, 1)
    with open(f"{OUT}/{name}", "w") as f:
        json.dump(RUN, f, indent=1)


def watchdog():
    event(f"WATCHDOG: {WATCHDOG_MIN} min cap reached, saving and exiting")
    try:
        save_run()
    finally:
        os._exit(3)


def sh(cmd):
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    return (r.stdout + r.stderr).strip()


def pip(*pkgs):
    cmd = [sys.executable, "-m", "pip", "install", "-q", "--disable-pip-version-check", *pkgs]
    t = time.time()
    r = subprocess.run(cmd, capture_output=True, text=True)
    tail = "\n".join((r.stdout + r.stderr).strip().splitlines()[-12:])
    if r.returncode:
        raise RuntimeError(f"pip install {' '.join(pkgs)} failed:\n{tail}")
    event(f"pip install {' '.join(pkgs)} ok in {time.time() - t:.0f}s")
    if tail:
        log("pip notes:\n" + tail)


def versions():
    import importlib.metadata as md
    out = {}
    for p in ("torch", "diffusers", "transformers", "accelerate", "huggingface_hub", "safetensors",
              "bitsandbytes", "sentencepiece", "numpy", "Pillow"):
        try:
            out[p] = md.version(p)
        except Exception:
            out[p] = None
    return out


def env_info():
    e = RUN["env"]
    e["python"] = sys.version.split()[0]
    e["nvidia_smi"] = sh("nvidia-smi --query-gpu=name,memory.total,driver_version --format=csv,noheader") or "none"
    e["nproc"] = os.cpu_count()
    e["mem_gib"] = sh("free -g | awk '/Mem:/ {print $2}'")
    for p in ("/tmp", "/kaggle/working"):
        if os.path.exists(p):
            s = os.statvfs(p)
            e[f"disk_free_gib_{p}"] = round(s.f_bavail * s.f_frsize / 2**30, 1)
    e["versions_before_pin"] = versions()
    event(f"env: {json.dumps(e)}")


def free_gpu():
    gc.collect()
    try:
        import torch
        if torch.cuda.is_available():
            for i in range(torch.cuda.device_count()):
                with torch.cuda.device(i):
                    torch.cuda.empty_cache()
    except Exception:
        pass


# ------------------------------------------------------------------ download

def download(patterns=PATTERNS):
    from huggingface_hub import snapshot_download
    last = None
    for repo, rev in REPOS:
        for attempt in (1, 2):
            try:
                t = time.time()
                snapshot_download(repo, revision=rev, local_dir=MODEL_DIR, allow_patterns=patterns, max_workers=8)
                secs = time.time() - t
                if not TEST and patterns is PATTERNS:
                    for rel, size in EXPECTED_BYTES.items():
                        got = os.path.getsize(f"{MODEL_DIR}/{rel}")
                        if got != size:
                            raise RuntimeError(f"{rel}: {got} bytes, expected {size}")
                RUN["totals"]["download_repo"] = f"{repo}@{rev}"
                RUN["totals"]["download_seconds"] = round(secs, 1)
                event(f"downloaded {repo}@{(rev or 'main')[:8]} in {secs:.0f}s")
                return
            except Exception as ex:
                last = ex
                event(f"download {repo} attempt {attempt} failed: {type(ex).__name__}: {str(ex)[:300]}")
    raise RuntimeError(f"all download sources failed: {last}")


# ------------------------------------------------------------------ GPU stages

def dev_names(n):
    if TEST:
        return "cpu", "cpu"
    return "cuda:0", ("cuda:1" if n > 1 else "cuda:0")


def encode_all(jobs, n):
    import torch
    from diffusers import FluxPipeline
    dev0, devt = dev_names(n)
    dtypes = [torch.float32] if TEST else [torch.bfloat16, torch.float16]
    last = None
    for dt in dtypes:
        pipe = None
        try:
            t = time.time()
            pipe = FluxPipeline.from_pretrained(MODEL_DIR, transformer=None, vae=None, dtype=dt)
            pipe.to(devt)
            event(f"text encoders loaded as {dt} on {devt} in {time.time() - t:.0f}s")
            res = {}
            for j in jobs:
                t = time.time()
                with torch.no_grad():
                    pe, pooled, _ = pipe.encode_prompt(prompt=j["prompt"], prompt_2=None, device=devt,
                                                       num_images_per_prompt=1, max_sequence_length=MAXSEQ)
                ntok = len(pipe.tokenizer_2(j["prompt"], truncation=False).input_ids)
                tgt = torch.float32 if TEST else torch.float16
                pe16, pooled16 = pe.to(tgt).cpu(), pooled.to(tgt).cpu()
                if not (torch.isfinite(pe16).all() and torch.isfinite(pooled16).all()):
                    raise RuntimeError(f"non-finite text embeddings for {j['id']} with {dt}")
                res[j["id"]] = (pe16, pooled16, ntok)
                log(f"encoded {j['id']} ({ntok} T5 tokens, {time.time() - t:.1f}s)")
            RUN["totals"]["text_encoder_dtype"] = str(dt)
            del pipe
            free_gpu()
            return res
        except Exception as ex:
            last = ex
            event(f"text encoding with {dt} failed: {type(ex).__name__}: {str(ex)[:300]}")
            log(traceback.format_exc())
            del pipe
            free_gpu()
    raise RuntimeError(f"text encoding failed: {last}")


class NonFinite(Exception):
    pass


def load_transformer(strategy, n):
    import torch
    from diffusers import FluxTransformer2DModel
    if strategy == "cpu_test":
        return FluxTransformer2DModel.from_pretrained(MODEL_DIR, subfolder="transformer", dtype=torch.float32)
    if strategy == "fp16_split":
        if n < 2:
            raise RuntimeError("fp16_split needs 2 GPUs")
        return FluxTransformer2DModel.from_pretrained(
            MODEL_DIR, subfolder="transformer", dtype=torch.float16, device_map="balanced",
            max_memory={i: "14GiB" for i in range(n)})
    if strategy == "nf4":
        pip(BNB_PIN)
        from diffusers import BitsAndBytesConfig
        q = BitsAndBytesConfig(load_in_4bit=True, bnb_4bit_quant_type="nf4", bnb_4bit_compute_dtype=torch.float16)
        return FluxTransformer2DModel.from_pretrained(
            MODEL_DIR, subfolder="transformer", quantization_config=q, dtype=torch.float16,
            device_map={"": 0})
    raise ValueError(strategy)


def device_summary(tf):
    dm = getattr(tf, "hf_device_map", None)
    if not dm:
        return None
    out = {}
    for d in dm.values():
        out[str(d)] = out.get(str(d), 0) + 1
    return out


def denoise_all(jobs, embeds, n):
    import torch
    from diffusers import FlowMatchEulerDiscreteScheduler, FluxPipeline
    strategies = ["cpu_test"] if TEST else ["fp16_split", "nf4"]
    dev0, _ = dev_names(n)
    latents, pending = {}, list(jobs)
    ngpu = 0 if TEST else n
    for strat in strategies:
        if not pending:
            break
        tf = pipe = None
        try:
            t = time.time()
            tf = load_transformer(strat, n)
            load_s = time.time() - t
            sched = FlowMatchEulerDiscreteScheduler.from_pretrained(MODEL_DIR, subfolder="scheduler")
            pipe = FluxPipeline(scheduler=sched, vae=None, text_encoder=None, tokenizer=None,
                                text_encoder_2=None, tokenizer_2=None, transformer=tf)
            pipe.set_progress_bar_config(disable=True)
            vram = [round(torch.cuda.memory_allocated(i) / 2**30, 2) for i in range(ngpu)]
            RUN["totals"].setdefault("strategies", {})[strat] = {
                "load_seconds": round(load_s, 1), "device_map_modules": device_summary(tf),
                "vram_after_load_gib": vram}
            event(f"strategy {strat}: transformer loaded in {load_s:.0f}s, VRAM after load {vram} GiB, "
                  f"modules per device {device_summary(tf)}")
        except Exception as ex:
            event(f"strategy {strat}: load failed: {type(ex).__name__}: {str(ex)[:400]}")
            log(traceback.format_exc())
            del tf, pipe
            free_gpu()
            continue
        first = True
        for j in list(pending):
            try:
                for i in range(ngpu):
                    torch.cuda.reset_peak_memory_stats(i)
                pe, pooled, ntok = embeds[j["id"]]
                g = torch.Generator("cpu").manual_seed(j["seed"])
                steps = 2 if TEST else STEPS
                t = time.time()
                lat = pipe(prompt_embeds=pe.to(dev0), pooled_prompt_embeds=pooled.to(dev0),
                           height=j["height"], width=j["width"], num_inference_steps=steps,
                           guidance_scale=GUIDANCE, max_sequence_length=MAXSEQ, generator=g,
                           output_type="latent").images
                for i in range(ngpu):
                    torch.cuda.synchronize(i)
                secs = time.time() - t
                if not torch.isfinite(lat).all():
                    raise NonFinite(f"non-finite latents for {j['id']}")
                peak = [round(torch.cuda.max_memory_allocated(i) / 2**30, 2) for i in range(ngpu)]
                latents[j["id"]] = lat.detach().cpu()
                pending.remove(j)
                RUN["images"].append({"set": j["set"], "id": j["id"], "seed": j["seed"],
                                      "width": j["width"], "height": j["height"], "steps": steps,
                                      "guidance": GUIDANCE, "strategy": strat, "prompt": j["prompt"],
                                      "t5_tokens": ntok, "t5_truncated": ntok > MAXSEQ,
                                      "denoise_seconds": round(secs, 1), "vram_peak_gib_per_gpu": peak,
                                      "first_image_of_strategy": first})
                event(f"{strat} {j['id']} {j['width']}x{j['height']}: denoise {secs:.1f}s, peak VRAM {peak} GiB"
                      + (" (includes CUDA warmup)" if first else ""))
                first = False
                save_run()
            except Exception as ex:
                event(f"strategy {strat}: {j['id']} failed: {type(ex).__name__}: {str(ex)[:400]}")
                log(traceback.format_exc())
                break  # drop the strategy, retry the rest with the next one
        del pipe, tf
        free_gpu()
    return latents


def decode_all(jobs, latents, n):
    import numpy as np
    import torch
    from diffusers import AutoencoderKL, FluxPipeline
    from PIL import Image
    dev0, _ = dev_names(n)
    ngpu = 0 if TEST else n
    vae = AutoencoderKL.from_pretrained(MODEL_DIR, subfolder="vae", dtype=torch.float32).to(dev0).eval()
    by_id = {r["id"]: r for r in RUN["images"]}
    for j in jobs:
        if j["id"] not in latents:
            continue
        rec = by_id[j["id"]]
        try:
            for i in range(ngpu):
                torch.cuda.reset_peak_memory_stats(i)
            t = time.time()
            z = FluxPipeline._unpack_latents(latents[j["id"]].to(dev0, torch.float32), j["height"], j["width"], VAE_SCALE)
            z = z / vae.config.scaling_factor + vae.config.shift_factor
            with torch.no_grad():
                try:
                    x = vae.decode(z, return_dict=False)[0]
                except torch.cuda.OutOfMemoryError:
                    free_gpu()
                    vae.enable_tiling()
                    x = vae.decode(z, return_dict=False)[0]
            arr = ((x[0].float() / 2 + 0.5).clamp(0, 1).permute(1, 2, 0).cpu().numpy() * 255).round().astype(np.uint8)
            os.makedirs(f"{OUT}/{j['set']}", exist_ok=True)
            path = f"{OUT}/{j['set']}/{j['id']}.png"
            Image.fromarray(arr).save(path)
            dsecs = time.time() - t
            rec.update({"decode_seconds": round(dsecs, 1), "seconds": round(rec["denoise_seconds"] + dsecs, 1),
                        "decode_vram_peak_gib_per_gpu": [round(torch.cuda.max_memory_allocated(i) / 2**30, 2) for i in range(ngpu)],
                        "file": f"{j['set']}/{j['id']}.png", "px": [arr.shape[1], arr.shape[0]],
                        "mean_rgb": [round(float(v), 1) for v in arr.reshape(-1, 3).mean(0)],
                        "pixel_std": round(float(arr.std()), 1)})
            if arr.std() < 3:
                rec["warning"] = "near-uniform image (possible black/NaN output)"
            log(f"decoded {j['id']} in {dsecs:.1f}s -> {path} (std {arr.std():.1f})")
        except Exception as ex:
            rec["decode_error"] = f"{type(ex).__name__}: {str(ex)[:300]}"
            event(f"decode {j['id']} failed: {rec['decode_error']}")
            log(traceback.format_exc())
        save_run()
    del vae
    free_gpu()


def main():
    t = threading.Timer(WATCHDOG_MIN * 60, watchdog)
    t.daemon = True
    t.start()
    os.makedirs(OUT, exist_ok=True)
    env_info()
    if not TEST:
        pip(*PINS)
    import torch
    n = torch.cuda.device_count()
    RUN["env"]["versions_after_pin"] = versions()
    RUN["env"]["gpu_count"] = n
    RUN["env"]["torch_cuda_build"] = getattr(torch.version, "cuda", None)
    for i in range(n):
        p = torch.cuda.get_device_properties(i)
        RUN["env"][f"gpu{i}"] = f"{p.name} {p.total_memory / 2**30:.1f} GiB sm_{p.major}{p.minor}"
    event(f"torch {torch.__version__} cuda {RUN['env']['torch_cuda_build']} gpus {n}")
    if n == 0 and not TEST:
        event("no CUDA device: this kernel needs a GPU")
        return 1
    jobs = list(PROMPTS)
    if TEST:
        jobs = [dict(j, width=128, height=128) for j in jobs[:2]]
    download()
    t = time.time()
    embeds = encode_all(jobs, n)
    RUN["totals"]["encode_all_seconds"] = round(time.time() - t, 1)
    save_run()
    latents = denoise_all(jobs, embeds, n)
    save_run()
    decode_all(jobs, latents, n)
    ok = sum(1 for r in RUN["images"] if r.get("file"))
    RUN["totals"]["images_ok"] = ok
    RUN["totals"]["images_requested"] = len(jobs)
    RUN["totals"]["failed"] = [j["id"] for j in jobs if j["id"] not in {r["id"] for r in RUN["images"] if r.get("file")}]
    secs = [r["seconds"] for r in RUN["images"] if "seconds" in r]
    if secs:
        RUN["totals"]["mean_seconds_per_image"] = round(sum(secs) / len(secs), 1)
    event(f"DONE: {ok}/{len(jobs)} images in {time.time() - T0:.0f}s total")
    save_run()
    return 0 if ok else 1


if __name__ == "__main__":
    code = 1
    try:
        code = main()
    except Exception:
        event("FATAL " + traceback.format_exc()[-1500:])
        try:
            save_run()
        except Exception:
            pass
    sys.stdout.flush()
    sys.exit(code)
